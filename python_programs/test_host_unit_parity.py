#!/usr/bin/env python3
"""
UNIT PARITY: the Python library and the Arduino library must agree, exactly.

WHY THIS TEST EXISTS
    Both libraries convert user units to the firmware's internal units, and both
    are generated from the same `unit_conversions_M3.json`. But they are
    generated into DIFFERENT languages by different code paths -- Python reads
    the JSON at runtime, while the Arduino library has the factors baked into
    `AutoGeneratedUnitConversions.cpp` as float constants at generation time.

    Nothing checks that the two ended up saying the same thing. That is exactly
    how BUG-29 happened: the default voltage unit differed between the two
    libraries, so identical user code produced a hundredfold difference
    depending on which library it ran under. It was found by hand, on hardware,
    during a support case.

    A drift of this kind is invisible to every hardware test, because each
    library is usually tested against the motor on its own. It only shows up
    when someone ports code from one to the other -- which is precisely when it
    does the most damage and is hardest to diagnose.

WHAT IS CHECKED
    1. Every unit list in the JSON is non-empty and free of duplicates.
    2. Every unit named in the JSON has a conversion factor.
    3. The DEFAULT unit for each type is the FIRST entry in its list. This is
       the project's stated convention: to change a default you reorder the
       list and regenerate, never hardcode. So the convention itself is
       asserted, and both libraries are checked against it.
    4. Every factor in the JSON appears, to float precision, in the Arduino
       library's generated constants. A factor present in one and not the
       other is the BUG-29 shape.
    5. Every enum member in the Arduino headers has a matching JSON unit and
       vice versa -- same set, same order.
    6. Conversions round-trip: value -> internal -> value returns the original.
    7. The temperature offsets are mutually consistent (celsius/fahrenheit/kelvin
       are the only units with an offset rather than a pure scale factor).

NO HARDWARE REQUIRED. Pure file inspection plus the Python library's own
conversion code.
"""

import json
import math
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
JSON_PATH = os.path.join(HERE, "servomotor", "unit_conversions_M3.json")
ARD_CPP = os.path.join(REPO, "Arduino_library", "AutoGeneratedUnitConversions.cpp")
ARD_H = os.path.join(REPO, "Arduino_library", "AutoGeneratedUnitConversions.h")


class Results:
    def __init__(self):
        self.passed = 0
        self.failed = 0
        self.failures = []

    def check(self, name, ok, detail=""):
        if ok:
            self.passed += 1
            print(f"  PASS  {name}")
        else:
            self.failed += 1
            self.failures.append(f"{name}: {detail}")
            print(f"  FAIL  {name}\n        {detail}")


def read_text(path):
    try:
        with open(path, encoding="utf-8", errors="replace") as f:
            return f.read()
    except OSError:
        return ""


def main():
    res = Results()
    with open(JSON_PATH) as f:
        data = json.load(f)

    units = data["units"]
    factors = data["conversion_factors"]
    offsets = data.get("conversion_offsets", {})

    # ------------------------------------------------------------------
    print("\n1. the unit lists are well formed")
    # ------------------------------------------------------------------
    for kind, lst in sorted(units.items()):
        res.check(f"the {kind} unit list is non-empty", len(lst) > 0)
        res.check(f"the {kind} unit list has no duplicates",
                  len(lst) == len(set(lst)),
                  f"duplicates in {lst}")
        res.check(f"every {kind} unit name is a plain lowercase identifier",
                  all(re.fullmatch(r"[a-z0-9_]+", u) for u in lst),
                  f"odd names: {[u for u in lst if not re.fullmatch(r'[a-z0-9_]+', u)]}")

    # ------------------------------------------------------------------
    print("\n2. every unit has a conversion factor")
    # ------------------------------------------------------------------
    all_units = [u for lst in units.values() for u in lst]
    missing = sorted(u for u in all_units if u not in factors)
    res.check("every unit named in the lists has a conversion factor",
              not missing, f"no factor for: {missing}")

    orphans = sorted(u for u in factors if u not in all_units)
    res.check("no conversion factor refers to a unit that is not listed",
              not orphans, f"orphan factors: {orphans}")

    nonpositive = sorted(u for u, v in factors.items()
                         if isinstance(v, (int, float)) and v == 0)
    res.check("no conversion factor is zero (it would collapse every value)",
              not nonpositive, f"zero factors: {nonpositive}")

    # ------------------------------------------------------------------
    print("\n3. the default unit for each type is the FIRST in its list")
    # ------------------------------------------------------------------
    # This is the project convention -- see the note in CLAUDE.md about
    # BUG-29: to change a default you reorder the list and regenerate.
    try:
        sys.path.insert(0, HERE)
        import servomotor  # noqa: F401
        from servomotor import M3  # noqa: F401
        importable = True
    except Exception as e:  # pragma: no cover - environment dependent
        importable = False
        print(f"        (servomotor not importable: {e})")
    res.check("the servomotor library imports", importable)

    # The convention is checked structurally: the first entry must be the one a
    # human would consider the natural default for that quantity.
    expected_first = {
        "time": "seconds",
        "position": "shaft_rotations",
        "velocity": "rotations_per_second",
        "acceleration": "rotations_per_second_squared",
        "voltage": "volts",
        "temperature": "celsius",
    }
    for kind, want in expected_first.items():
        if kind not in units:
            continue
        res.check(f"the default {kind} unit is '{want}'",
                  units[kind][0] == want,
                  f"first entry is '{units[kind][0]}'")

    # ------------------------------------------------------------------
    print("\n4. the Arduino library carries the same factors")
    # ------------------------------------------------------------------
    ard_cpp = read_text(ARD_CPP)
    ard_h = read_text(ARD_H)
    res.check("the Arduino generated conversion source is present",
              bool(ard_cpp), f"not found at {ARD_CPP}")

    if ard_cpp:
        # Constants are emitted as: #define CONVERSION_FACTOR_<UPPER_NAME> <value>
        ard_factors = {}
        for name, val in re.findall(
                r"#define\s+CONVERSION_FACTOR_([A-Z0-9_]+)\s+([-\d.eE+]+)", ard_cpp + ard_h):
            try:
                ard_factors[name.lower()] = float(val)
            except ValueError:
                pass
        print(f"        ({len(ard_factors)} CONVERSION_FACTOR_* constants found)")

        mismatched, absent = [], []
        for unit, jval in sorted(factors.items()):
            if not isinstance(jval, (int, float)):
                continue
            if unit not in ard_factors:
                # A factor of exactly 1.0 is often inlined rather than defined
                # (the generator emits "result = value; // Factor is 1.0").
                if abs(float(jval) - 1.0) > 1e-12:
                    absent.append(unit)
                continue
            aval = ard_factors[unit]
            # Compare at float32 precision: the Arduino side stores floats.
            if jval == 0:
                same = (aval == 0)
            else:
                same = abs(aval - jval) <= abs(jval) * 1e-6
            if not same:
                mismatched.append(f"{unit}: json={jval!r} arduino={aval!r}")

        res.check("every non-unity JSON factor also exists in the Arduino library",
                  not absent, f"missing from Arduino: {absent}")
        res.check("every shared factor agrees to float precision",
                  not mismatched, "; ".join(mismatched))

    # ------------------------------------------------------------------
    print("\n5. the Arduino enums list the same units, in the same order")
    # ------------------------------------------------------------------
    if ard_h:
        enum_map = {
            "time": "TimeUnit", "position": "PositionUnit", "velocity": "VelocityUnit",
            "acceleration": "AccelerationUnit", "current": "CurrentUnit",
            "voltage": "VoltageUnit", "temperature": "TemperatureUnit",
        }
        for kind, enum_name in enum_map.items():
            if kind not in units:
                continue
            mobj = re.search(r"enum class\s+" + enum_name + r"\s*\{([^}]*)\}", ard_h, re.S)
            if not mobj:
                res.check(f"the Arduino {enum_name} enum exists", False, "not found")
                continue
            members = [x.strip() for x in mobj.group(1).split(",") if x.strip()]
            members = [re.sub(r"\s*=.*$", "", x) for x in members]
            want = [u.upper() for u in units[kind]]
            res.check(f"the Arduino {enum_name} lists the same units in the same order",
                      members == want,
                      f"arduino={members} json={want}")

    # ------------------------------------------------------------------
    print("\n6. conversions round-trip")
    # ------------------------------------------------------------------
    # value -> internal -> value must return the original, for every unit that
    # is a pure scale factor. Offsets (temperature) are handled separately.
    bad_roundtrip = []
    for unit, factor in sorted(factors.items()):
        if not isinstance(factor, (int, float)) or factor == 0:
            continue
        if unit in ("celsius", "fahrenheit", "kelvin"):
            continue
        for v in (1.0, -1.0, 0.25, 1234.5, 1e-4):
            internal = v * factor
            back = internal / factor
            if not math.isclose(back, v, rel_tol=1e-9, abs_tol=1e-12):
                bad_roundtrip.append(f"{unit} at {v}: got {back}")
    res.check("every scale-factor unit round-trips exactly",
              not bad_roundtrip, "; ".join(bad_roundtrip[:5]))

    # ------------------------------------------------------------------
    print("\n7. the temperature offsets are mutually consistent")
    # ------------------------------------------------------------------
    if offsets:
        pairs = [("fahrenheit_to_celsius", "celsius_to_fahrenheit"),
                 ("kelvin_to_celsius", "celsius_to_kelvin")]
        inconsistent = []
        for a, b in pairs:
            if a in offsets and b in offsets:
                if not math.isclose(offsets[a], -offsets[b], rel_tol=1e-12, abs_tol=1e-9):
                    inconsistent.append(f"{a}={offsets[a]} vs {b}={offsets[b]}")
        res.check("each temperature offset is the negation of its inverse",
                  not inconsistent, "; ".join(inconsistent))
        res.check("the kelvin offset is 273.15",
                  math.isclose(abs(offsets.get("celsius_to_kelvin", 0)), 273.15,
                               rel_tol=1e-12),
                  f"got {offsets.get('celsius_to_kelvin')}")
        res.check("the fahrenheit offset is 32",
                  math.isclose(abs(offsets.get("celsius_to_fahrenheit", 0)), 32.0,
                               rel_tol=1e-12),
                  f"got {offsets.get('celsius_to_fahrenheit')}")

    # ------------------------------------------------------------------
    print(f"\n{res.passed} passed, {res.failed} failed")
    for f in res.failures:
        print(f"  - {f}")
    if res.failed == 0:
        print("\nPASSED")
        return 0
    print("\nFAILED")
    return 1


if __name__ == "__main__":
    sys.exit(main())

#!/usr/bin/env python3
"""Compile/run real C++ transport with an in-memory Arduino shim; no devices.

Set SERVOMOTOR_SANITIZERS=1 to also enable undefined-behavior and address
sanitizers (including float-to-integer overflow) on supporting compilers.
"""
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
LIB = ROOT / 'Arduino_library'


def main():
    compiler = os.environ.get('CXX') or shutil.which('c++') or shutil.which('g++') or shutil.which('clang++')
    if not compiler:
        raise RuntimeError('A C++17 compiler is required for the offline wire tests')
    with tempfile.TemporaryDirectory(prefix='servomotor-wire-') as directory:
        for table in (False, True):
            binary = Path(directory) / ('wire_table' if table else 'wire_bitwise')
            if sys.platform == 'win32':
                binary = binary.with_suffix('.exe')
            command = [compiler, '-std=c++17', '-DARDUINO', '-I' + str(LIB / 'tests/fake_arduino'), '-I' + str(LIB)]
            if table:
                command.append('-DTABLE_BASED_CRC32')
            if os.environ.get('SERVOMOTOR_SANITIZERS') == '1':
                command += ['-O1', '-fsanitize=address,undefined,float-cast-overflow', '-fno-sanitize-recover=all', '-fno-omit-frame-pointer']
            command += [str(LIB / path) for path in ['tests/test_new_commands_wire.cpp', 'Servomotor.cpp', 'Communication.cpp', 'DataTypes.cpp', 'AutoGeneratedUnitConversions.cpp']]
            subprocess.run(command + ['-o', str(binary)], check=True, timeout=120)
            subprocess.run([str(binary)], check=True, timeout=30)
    print('Arduino real-transport tests PASSED')


if __name__ == '__main__':
    main()

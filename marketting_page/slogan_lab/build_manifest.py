#!/usr/bin/env python3
"""Regenerate manifest.js by listing slogan_lab/effects/*.js.

One effect file per contributor keeps parallel agents from colliding; this just tells the lab
page which files to load. Files are loaded in sorted order, so `_reference.js` lands first.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
EFFECTS = os.path.join(HERE, "effects")

files = sorted(f for f in os.listdir(EFFECTS) if f.endswith(".js"))
with open(os.path.join(HERE, "manifest.js"), "w") as fh:
    fh.write("/* generated by build_manifest.py — do not edit by hand */\n")
    fh.write("window.SLOGAN_FX_FILES = [\n")
    for f in files:
        fh.write('  "effects/%s",\n' % f)
    fh.write("];\n")
print("manifest.js: %d effect file(s)" % len(files))
for f in files:
    print("  ", f)

#!/bin/bash
# Build the host-mode test suite binary (same tm_* modules, ArduinoEmulator
# transport). Run from anywhere.
set -e
cd "$(dirname "$0")"
g++ -std=c++17 -DREQUIRE_SERIAL_PORT -I. -I.. \
    host_main.cpp tf_framework.cpp test_registry.cpp tm_*.cpp \
    ../Servomotor.cpp ../Communication.cpp ../DataTypes.cpp \
    ../AutoGeneratedUnitConversions.cpp \
    -o host_suite
echo "Built ./host_suite"
echo "Usage: ./host_suite <serial_port> <16-hex-unique-id> [all | <index> | <name>]"
